/* Content-addressed static releases. Business source files are kept unchanged. */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
const root=path.dirname(fileURLToPath(import.meta.url));
const modules=[['runtime','app-runtime.js',true],['sdk','vendor/supabase-2.117.2.js',true],
 ['gestures','home-gestures.js'],['kitchen-catalog','kitchen-recipes.js'],['kitchen-api','kitchen-api.js'],
 ['kitchen','kitchen.js'],['family','family.js'],['fat','fat-loss.js'],['rewards','fat-rewards.js'],['access','device-access.js',true],
 ['push','web-push.js'],['notifications','notifications.js'],['app','app.js',true],['theme','ui-theme.js']];
const styles=['fat-loss.css','fat-rewards.css','ui-theme.css','kitchen.css','web-push.css','device-access.css','notifications.css','kitchen-refined.css','family.css'];
const hash=text=>createHash('sha256').update(text).digest('hex');
export async function bundle({build,updatedAt,sdkSource,overrides={}}={}) {
 const previous=JSON.parse(await fs.readFile(path.join(root,'version.json'),'utf8').catch(()=>'{}'));
 const now=new Date(),day=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Shanghai',year:'numeric',month:'2-digit',day:'2-digit'}).format(now).replaceAll('-','');
 build ||= previous.build?.startsWith(day+'.')?`${day}.${Number(previous.build.split('.')[1])+1}`:`${day}.1`;
 updatedAt ||= now.toISOString();
 if(!/^\d{8}\.\d+$/.test(build)||!Number.isFinite(Date.parse(updatedAt)))throw Error('Invalid release metadata');
 const displayTime=new Intl.DateTimeFormat('zh-CN',{timeZone:'Asia/Shanghai',year:'numeric',month:'2-digit',day:'2-digit',hour:'2-digit',minute:'2-digit',hour12:false}).format(new Date(updatedAt));
 const read=async file=>(overrides[file]??await fs.readFile(path.join(root,file),'utf8')).replace(/\r\n?/g,'\n');
 const safe=text=>text.replace(/<\/script/gi,'<\\/script');
 const files=new Map(),assets=[];
 const asset=(id,type,content)=>{
  const sha256=hash(content),url=`assets/${id}.${sha256}.${type}`,bytes=Buffer.byteLength(content);
  const descriptor={url,sha256,bytes};files.set(url,content);assets.push(descriptor);
  return {...descriptor,integrity:'sha256-'+Buffer.from(sha256,'hex').toString('base64')};
 };
 let template=await read('index.source.html'),baseIndex=0;
 // Bind before stylesheet requests: an uncontrolled first visit must also recover from partial publication.
 template=template.replace(/<head\b[^>]*>/,head=>head+`<script>window.addEventListener('error',event=>{const element=event.target;if(element&&(element.src||element.href||'').includes('/assets/'))window.PointsReleaseLoadFailed=true;},true);</script>`);
 template=template.replace(/<style\b([^>]*)>([\s\S]*?)<\/style>/g,(_all,attrs,css)=>{
  const a=asset(`base-${baseIndex++}`,'css',css);return `<link rel="stylesheet" href="${a.url}" integrity="${a.integrity}"${attrs}/>`;
 });
 const css=[];
 for(const file of styles){const a=asset(file.replace('.css',''),'css',await read(file));css.push(`<link rel="stylesheet" href="${a.url}" integrity="${a.integrity}"/>`);}
 let scripts=`<script data-points-asset="startup">${safe(await read('startup.js'))}</script>\n`;
 for(const [id,file,required=false] of modules){
  const source=id==='sdk'&&sdkSource?sdkSource:await read(file);new Function(source);
  const content=`if(window.PointsStartup.canStart()){try{\n${source}\n}catch(error){window.PointsStartup.fail(${JSON.stringify(id)},error,${required});}}\n`;
  const a=asset(id,'js',content);
  scripts+=`<script data-points-asset="${id}" src="${a.url}" integrity="${a.integrity}" onerror="window.PointsStartup.fail('${id}',new Error('Asset unavailable'),${required})"></script>\n`;
 }
 scripts+=`<script>window.PointsStartup.finish();</script>\n<script>${safe(await read('updates.js'))}</script>`;
 const html='<!-- Generated by points/build.mjs; edit module sources, then rebuild. -->\n'+template
  .replace('<!-- POINTS_STYLES -->',()=>css.join('\n')).replace('<!-- POINTS_SCRIPTS -->',()=>scripts)
  .replaceAll('__POINTS_BUILD__',build).replaceAll('__POINTS_UPDATED_AT__',displayTime);
 const shell={url:`assets/shell.${hash(html)}.html`,sha256:hash(html),bytes:Buffer.byteLength(html)};
 files.set(shell.url,html);
 const release={schema:2,build,updatedAt,shell,assets};
 const worker=(await read('sw.source.js')).replaceAll('__POINTS_BUILD__',build).replaceAll('__POINTS_RELEASE_JSON__',JSON.stringify(release));
 return {html,build,updatedAt,worker,release,files};
}
async function writeBatches(file,text){
 await fs.mkdir(path.dirname(path.join(root,file)),{recursive:true});const handle=await fs.open(path.join(root,file),'w');
 try{const lines=text.split('\n');for(let i=0;i<lines.length;i+=200)await handle.write(lines.slice(i,i+200).join('\n')+(i+200<lines.length?'\n':''));}finally{await handle.close();}
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const result=await bundle({build:process.argv[2],updatedAt:process.argv[3]});
 for(const [file,content] of result.files)await writeBatches(file,content);
 await writeBatches('index.html',result.html);await writeBatches('sw.js',result.worker);
 await writeBatches('version.json',JSON.stringify(result.release,null,2)+'\n');
 console.log(`Release ${result.build}: shell ${Buffer.byteLength(result.html)} bytes (gzip ${gzipSync(result.html).length}), ${result.release.assets.length} independently cached assets.`);
}
